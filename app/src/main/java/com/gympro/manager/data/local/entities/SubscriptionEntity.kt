package com.gympro.manager.data.local.entities

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.gympro.manager.model.PaymentMethod
import com.gympro.manager.model.SubscriptionType

/**
 * سجل اشتراك واحد لعضو معيّن.
 * بالنسبة للاشتراك اليومي: تُنشأ سجلّة جديدة لكل يوم حضور (startDate = endDate = يوم الحضور).
 * بالنسبة للأسبوعي والشهري: سجلّة واحدة تغطي كامل المدة بسعر ثابت.
 */
@Entity(
    tableName = "subscriptions",
    foreignKeys = [ForeignKey(
        entity = MemberEntity::class,
        parentColumns = ["id"],
        childColumns = ["memberId"],
        onDelete = ForeignKey.SET_NULL
    )],
    indices = [Index("memberId")]
)
data class SubscriptionEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    // Nullable: عند حذف عضو نهائياً، تُفصَل اشتراكاته المدفوعة عنه (memberId = NULL) بدل
    // حذفها. سابقاً كان onDelete = CASCADE يحذف كل اشتراكات العضو تلقائياً عند حذفه، بما
    // فيها الاشتراكات المدفوعة (isPaid = 1) التي تُعتبر المصدر الوحيد لأرقام تقارير
    // الإيرادات (revenueBetween/revenueBetweenByType لا تُصفّي حسب isDeleted عمداً)، فكانت
    // كل عملية حذف عضو تُقلّص إجمالي الإيرادات التاريخية بصمت ودون أي أثر. راجع
    // GymRepository.permanentDeleteMember() لمنطق الحذف الجديد.
    val memberId: Long?,
    val type: SubscriptionType,
    val price: Double,
    val startDate: Long,
    val endDate: Long,
    val isPaid: Boolean = false,
    val createdAt: Long = System.currentTimeMillis(),
    /**
     * تاريخ التحصيل الفعلي للدفعة (متى استلم صاحب الجيم المال فعلياً)، وليس تاريخ إنشاء
     * السجل. تبقى null طالما الاشتراك غير مدفوع.
     *
     * لماذا هذا الحقل ضروري ولا يكفي استخدام createdAt للإيرادات:
     * سجل الاشتراك يُنشأ أحياناً وهو *غير مدفوع* (دَين)، ثم يُسدَّد لاحقاً بعد أسابيع أو
     * أشهر عبر تبديل مفتاح "مدفوع" (من شاشة تعديل العضو أو togglePaidStatus). لو استمرت
     * تقارير الإيرادات بالاعتماد على createdAt وحده، فإن أي دَين قديم يُحصَّل اليوم سيظهر
     * إيراداً في الشهر الذي *أُنشئ* فيه الاشتراك (ربما تقرير مُقفَل من أشهر)، لا في الشهر
     * الذي *استُلم* فيه المبلغ فعلياً — فيختل تطابق تقرير الإيرادات مع صندوق النقدية
     * الفعلي كل شهر، ويتغيّر رقم إيراد شهر سابق بصمت بعد أن يكون صاحب الجيم قد راجعه
     * واعتمده. هذه المشكلة لا تظهر إلا بعد أن يبدأ التطبيق يُستخدم لأشهر مع ديون حقيقية.
     *
     * القاعدة: paidAt = null طالما isPaid = false. عند التحول من غير مدفوع إلى مدفوع
     * تُضبط paidAt = "الآن" (لحظة التحصيل الحقيقية). عند إنشاء اشتراك مدفوعاً من البداية
     * (الحالة الشائعة)، paidAt = createdAt لأن التحصيل حدث فور الإنشاء. راجع
     * GymRepository.resolvePaidAt() لمنطق الحساب الموحّد.
     */
    val paidAt: Long? = null,
    /**
     * "يوم الفوترة المرجعي" (1-31) لهذا الاشتراك — ذو معنى فقط عندما type = MONTHLY.
     * يُحدَّد مرة واحدة عند أول اشتراك شهري للعضو (يوم الشهر الذي انضمّ فيه)، ثم يُورَّث
     * كما هو في كل تجديد لاحق، بدل إعادة اشتقاقه من تاريخ البدء الفعلي في كل مرة.
     *
     * لماذا هذا ضروري: بدون هذا الحقل، عضو ينضم في 31 يناير يحصل أول شهر على 27 يوماً فقط
     * (لأن فبراير أقصر)، ثم يتجدد الاشتراك التالي من تاريخ الانتهاء الفعلي (28 فبراير)
     * فيصبح "يوم الفوترة" الفعلي 27/28 بشكل دائم ولا يعود أبداً إلى 31 — انزلاق تراكمي
     * صامت في تاريخ الفوترة يظهر فقط بعد عدة أشهر من الاستخدام الحقيقي.
     * بوجود billingAnchorDay، يُحاول كل شهر العودة لليوم 31 (أو آخر يوم ممكن في الشهر
     * القصير)، فلا يتراكم الانزلاق ولا يفقد صاحب الجيم أياماً مدفوعة بشكل ممنهج.
     */
    val billingAnchorDay: Int = 0,
    /**
     * طريقة الدفع المستخدمة (أو المتوقَّعة) لتسديد هذا الاشتراك تحديداً — حقل معلوماتي بحت
     * لا علاقة له بـ isPaid ولا بأي حساب إيراد؛ يصف فقط "كيف" وليس "هل". راجع
     * PaymentMethod.kt للشرح الكامل ولماذا PALPAY هي القيمة الافتراضية.
     *
     * كل الاشتراكات المُنشأة قبل إضافة هذا الحقل (MIGRATION_5_6) تُعامَل تلقائياً
     * كـ PALPAY، تماماً كالقيمة الافتراضية هنا.
     */
    val paymentMethod: PaymentMethod = PaymentMethod.PALPAY,
    /**
     * اسم الشخص الذي أرسل المبلغ فعلياً عبر الدفع الإلكتروني — حقل اختياري بحت، مستقل
     * تماماً عن isPaid وعن paymentMethod. يُستخدم لمطابقة التحويل الوارد بالعضو المعني
     * عندما يكون المُرسِل شخصاً آخر غير العضو نفسه (حالة شائعة: ولي أمر يدفع عن ابنه).
     *
     * null افتراضياً لكل الاشتراكات المُنشأة قبل إضافة هذا الحقل (MIGRATION_6_7) ولأي
     * اشتراك جديد لم يُدخَل له اسم مُرسِل. لا علاقة له بأي حساب إيراد أو حالة دفع.
     */
    val senderName: String? = null,
    /**
     * رقم جوال الشخص الذي أرسل المبلغ فعلياً عبر الدفع الإلكتروني — نفس منطق [senderName]
     * تماماً وله نفس الغرض (مطابقة التحويل)، حقل معلوماتي اختياري لا يدخل في أي حساب.
     */
    val senderPhone: String? = null,
    /**
     * المبلغ المدفوع فعلياً عند "الدفع الجزئي" (Partial Payment) — ذو معنى فقط عندما
     * isPaid = false. null أو 0 تعني اشتراكاً غير مدفوع بالكامل (UNPAID)؛ قيمة أكبر من 0
     * تعني أن جزءاً من السعر دخل فعلياً في الإيراد بينما الباقي (price - paidAmount) لا يزال
     * دَيناً (PARTIAL). راجع PaymentStatus.kt للحالة الثلاثية الكاملة المُشتقّة من هذا الحقل
     * ومن isPaid معاً.
     *
     * لماذا لا نُضيف عمود status منفصل بدلاً من ذلك: PaymentStatus كلّه قابل للاشتقاق من
     * isPaid + paidAmount بلا أي غموض (راجع SubscriptionEntity.paymentStatus())، فإضافة عمود
     * إضافي كان سيخلق مصدرَي حقيقة قد يتعارضان (مثال: status = PARTIAL بينما isPaid = true)
     * يجب مزامنتهما يدوياً في كل مسار كتابة بدل الاعتماد على قاعدة اشتقاق واحدة موثوقة.
     *
     * عند التحول لاحقاً إلى PAID (تسديد كامل الدَّين المتبقي)، يُعاد ضبط هذا الحقل إلى null
     * لأن السعر الكامل price يُغني عنه تماماً — راجع GymRepository.resolvePaymentFields().
     * كل الاشتراكات المُنشأة قبل إضافة هذا الحقل (MIGRATION_7_8) تُعامَل تلقائياً كـ null،
     * أي UNPAID أو PAID بحسب isPaid المحفوظ مسبقاً كما كان تماماً — لا تغيير لأي بيانات قديمة.
     */
    val paidAmount: Double? = null
)
